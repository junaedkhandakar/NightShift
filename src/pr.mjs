// Push a finished branch and open a pull request for it.
//
// Two ways to reach GitHub, both optional:
//   1. `gh` (GitHub CLI)  -> creates the PR for you.
//   2. plain git + compare URL -> you click and finish it manually.
//
// Everything here is best effort. A missing `gh`, an unauthenticated shell, or
// a repo without a remote must never fail the overnight run: the branch is
// still on disk, and the URL is printed so the work is never lost.

import { execFileSync } from "node:child_process";

import * as G from "./git.mjs";

export function ghVersion() {
  try {
    return execFileSync("gh", ["--version"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    })
      .trim()
      .split("\n")[0];
  } catch {
    return null;
  }
}

export function remoteUrl(cwd, remote = "origin") {
  const raw = G.git(cwd, ["remote", "get-url", remote], { allowFail: true });
  if (!raw) return null;
  return raw.trim().replace(/\.git$/, "");
}

/** The branch GitHub will open the PR against, when it can be detected. */
export function defaultBranch(cwd) {
  const raw = G.git(cwd, ["symbolic-ref", "--quiet", "refs/remotes/origin/HEAD"], {
    allowFail: true,
  });
  if (!raw) return null;
  return raw.trim().replace(/^refs\/remotes\/origin\//, "");
}

/** Push the branch and set its upstream. Returns false when it cannot. */
export function pushBranch(cwd, branch, remote = "origin") {
  const out = G.git(cwd, ["push", "--set-upstream", remote, branch], { allowFail: true });
  return out !== null;
}

export function compareUrl(cwd, branch, base, remote = "origin") {
  const repo = remoteUrl(cwd, remote);
  if (!repo) return null;
  return `${repo}/compare/${base || defaultBranch(cwd) || "main"}...${branch}?expand=1`;
}

/**
 * Open a pull request for `branch`.
 *
 * Returns { ok, url, reason }. `url` is always set when a remote exists, so
 * the caller can print a link even when the PR could not be created.
 */
export function createPullRequest({
  cwd,
  branch,
  base = null,
  title,
  body,
  draft = false,
  remote = "origin",
}) {
  const url = compareUrl(cwd, branch, base, remote);

  if (!ghVersion()) {
    return { ok: false, reason: "GitHub CLI (gh) is not installed", url };
  }

  const args = ["pr", "create", "--head", branch, "--title", title, "--body", body];
  if (base) args.push("--base", base);
  if (draft) args.push("--draft");

  try {
    const out = execFileSync("gh", args, {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
    return { ok: true, url: out.trim() || url, reason: null };
  } catch (err) {
    const reason = (err.stderr || err.message || "")
      .toString()
      .trim()
      .split("\n")[0];
    return { ok: false, reason: reason || "gh pr create failed", url };
  }
}

/** Build the PR body from a finished task result. */
export function buildPullRequestBody({ id, task, stat, gate, costUSD, durationMs, harness }) {
  const lines = [
    `NightShift completed \`${id}\` overnight.`,
    "",
    "### Task",
    "",
    "```md",
    (task || "(task text not available)").trim(),
    "```",
    "",
  ];

  if (stat) lines.push("### Diff", "", "```", stat.trim(), "```", "");
  if (gate) lines.push(`**Gate:** \`${gate}\``, "");
  if (harness) lines.push(`**Harness:** \`${harness}\``);
  if (costUSD) lines.push(`**Cost:** $${Number(costUSD).toFixed(2)}`);
  if (durationMs) lines.push(`**Duration:** ${Math.round(durationMs / 1000)}s`);

  lines.push(
    "",
    "---",
    "",
    "_Generated by [NightShift](https://github.com/junaedkhandakar/NightShift). Review the diff before merging._",
  );

  return lines.join("\n");
}
